import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import chokidar from 'chokidar';
import { glob } from 'glob';

// __dirname equivalent in ESM
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Paths
const TEMPLATES_DIR = path.resolve(__dirname, '../templates');
const SCSS_OUTPUT_FILE = path.resolve(__dirname, '../styles/forwarded.scss');
const runOnce = process.argv.includes('--once');
const SCSS_HEADER = '// Auto-generated by scripts/watch-assets.js. Do not edit manually.\n';

const updateStyles = async () => {
    try {
        const files = (await glob('**/*.scss', { cwd: TEMPLATES_DIR, posix: true }))
            .map((file) => file.replace(/\\/g, '/'))
            .sort();

        const content = files.map((file) => `@forward "@templates/${file}";`).join('\n') + '\n';

        fs.writeFileSync(SCSS_OUTPUT_FILE, SCSS_HEADER + content);
        console.log(`[watch-assets] Updated ${path.basename(SCSS_OUTPUT_FILE)} with ${files.length} files.`);
    } catch (error) {
        console.error('[watch-assets] Error updating styles:', error);
    }
};

const watch = async () => {
    if (!fs.existsSync(TEMPLATES_DIR)) {
        console.warn(`[watch-assets] Templates directory not found: ${TEMPLATES_DIR}`);
        return;
    }

    console.log(`[watch-assets] Watching ${TEMPLATES_DIR}...`);

    // Initial sync
    await updateStyles();

    if (runOnce) {
        return;
    }

    const watcher = chokidar.watch(TEMPLATES_DIR, {
        ignored: /(^|[/\\])\../, // ignore dotfiles
        persistent: true,
        ignoreInitial: true // we did initial sync manually
    });

    watcher.on('all', (event, filePath) => {
        if (filePath.endsWith('.scss')) updateStyles();
    });

    watcher.on('error', (error) => console.error(`[watch-assets] Watcher error: ${error}`));
};

await watch();
